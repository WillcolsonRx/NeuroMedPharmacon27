-- Run once in the Supabase SQL Editor before enabling submissions.
-- These tables are server-only: no anon/authenticated grants or client policies.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  full_name text not null, email text not null, phone text, affiliation text not null default '',
  category text not null, tier text not null, workshop integer default 0,
  amount numeric not null, currency text default 'INR', ref_id text unique,
  payment_ref text, payment_proof text, proof_filename text, proof_mimetype text,
  proof_size integer, proof_uploaded_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.abstracts (
  id bigint generated by default as identity primary key,
  full_name text not null, email text not null, title text not null,
  category text, body text not null, ref_id text unique,
  created_at timestamptz not null default now()
);
create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text, email text, message text,
  created_at timestamptz not null default now()
);
create table if not exists public.sponsorships (
  id bigint generated by default as identity primary key,
  company_name text not null, contact_person text not null, email text not null,
  phone text, tier text not null, amount numeric not null, notes text,
  ref_id text unique, payment_ref text, payment_proof text,
  created_at timestamptz not null default now()
);
create table if not exists public.mail_logs (
  id bigint generated by default as identity primary key,
  recipient text not null, subject text not null, type text not null,
  ref_id text, status text not null, message_id text, error_msg text,
  created_at timestamptz not null default now()
);
alter table public.registrations enable row level security;
alter table public.abstracts enable row level security;
alter table public.contacts enable row level security;
alter table public.sponsorships enable row level security;
alter table public.mail_logs enable row level security;
revoke all on public.registrations, public.abstracts, public.contacts,
  public.sponsorships, public.mail_logs from anon, authenticated;
grant all on public.registrations, public.abstracts, public.contacts,
  public.sponsorships, public.mail_logs to service_role;
grant usage, select on all sequences in schema public to service_role;
